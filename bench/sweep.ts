// Combines the on-device and cloud runs and sweeps the routing threshold. Every number comes from
// bench/results/edge.json and bench/results/cloud.json. Writes bench/results/RESULTS.md.
import fs from 'node:fs';
import { evaluate, Item } from '../src/router/router';
import { matchLabel } from '../src/router/labels';

const edge = JSON.parse(fs.readFileSync('bench/results/edge.json', 'utf8'));
const cloud = JSON.parse(fs.readFileSync('bench/results/cloud.json', 'utf8'));
const byFile = new Map(cloud.rows.map((r: any) => [r.file, r]));
const items: Item[] = edge.rows.map((e: any) => {
  const c: any = byFile.get(e.file);
  // map the cloud's raw answer with the current matcher, so the mapping is reproducible from the raw text
  return { label: e.label, inCatalog: e.inCatalog, edgePred: e.pred, edgeConf: e.confidence, edgeMs: e.ms, cloudPred: matchLabel(c.raw, cloud.labels), cloudMs: c.ms, cloudBytes: c.requestBytes };
});
const pct = (x: number) => (Number.isNaN(x) ? 'n/a' : `${(x * 100).toFixed(1)}%`);
const q = (v: number[], p: number) => { const s = [...v].sort((a, b) => a - b); return s[Math.floor(p * (s.length - 1))]; };
const thresholds = [0, 0.3, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9, 0.95, 1.01];
const pts = thresholds.map((t) => evaluate(items, t));
const nIn = items.filter((i) => i.inCatalog).length, nOut = items.length - nIn;
const edgeOnlyIn = items.filter((i) => i.inCatalog && i.edgePred === i.label).length / nIn;
const cloudIn = items.filter((i) => i.inCatalog && i.cloudPred === i.label).length / nIn;
const cloudOut = items.filter((i) => !i.inCatalog && i.cloudPred === i.label).length / nOut;
const confIn = items.filter((i) => i.inCatalog).map((i) => i.edgeConf), confOut = items.filter((i) => !i.inCatalog).map((i) => i.edgeConf);
const md = [
  '# Results', '',
  `Generated by \`npx vite-node bench/sweep.ts\` from \`bench/results/edge.json\` (${edge.date}) and \`bench/results/cloud.json\` (${cloud.date}). Do not edit by hand.`, '',
  `${items.length} product photos: ${nIn} from the 15 catalog categories the device knows, ${nOut} from 15 categories it does not ("out of catalog"). `
  + `On-device: ${edge.model}. Cloud tier: ${cloud.model}; it is asked to choose among all 30 categories.`, '',
  '## Each tier alone', '',
  '| Tier | Accuracy, catalog items | Accuracy, out-of-catalog items | Median latency | Bytes sent per query |', '| --- | --- | --- | --- | --- |',
  `| On-device only | ${pct(edgeOnlyIn)} | 0% (it only knows the catalog) | ${q(items.map((i) => i.edgeMs), 0.5).toFixed(0)} ms | 0 |`,
  `| Cloud only | ${pct(cloudIn)} | ${pct(cloudOut)} | ${q(items.map((i) => i.cloudMs), 0.5).toFixed(0)} ms (CPU proxy) | ${q(items.map((i) => i.cloudBytes), 0.5).toLocaleString()} |`, '',
  `On-device confidence, median: catalog items ${q(confIn, 0.5).toFixed(2)}, out-of-catalog items ${q(confOut, 0.5).toFixed(2)}.`, '',
  '## Routing threshold sweep', '',
  'Answer on the device when its confidence is at least the threshold, otherwise escalate (an escalated query pays for both tiers).', '',
  '| Threshold | Escalated | Escalated, out-of-catalog | Accuracy | Catalog | Out-of-catalog | p50 latency | p95 latency | KB sent per query |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ...pts.map((p) => `| ${p.threshold > 1 ? 'always escalate' : p.threshold === 0 ? 'never escalate' : p.threshold} | ${pct(p.escalated)} | ${pct(p.escalatedOut)} | ${pct(p.accuracy)} | ${pct(p.accuracyIn)} | ${pct(p.accuracyOut)} | ${p.p50Ms.toFixed(0)} ms | ${p.p95Ms.toFixed(0)} ms | ${p.kbPerQuery.toFixed(1)} |`),
  '', 'Latency is measured in a 2-core container: the on-device tier in headless Chromium (WASM, no GPU), the cloud tier on the same CPU. Both are proxies for their real counterparts; the shape of the trade-off is the result, not the absolute times.', '',
].join('\n');
fs.writeFileSync('bench/results/RESULTS.md', md);
fs.writeFileSync('bench/results/sweep.json', JSON.stringify(pts, null, 2) + '\n');
console.log(md);
